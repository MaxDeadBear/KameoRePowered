"""Matches the vanilla game's functions to the title update's, by their instructions with addresses masked.

Writes map.json ({vanilla hex: tu hex}) and prints how much of each side matched. Rounds:
 1. whole-function signature, addresses and data offsets masked, unique on both sides;
 2. same with every immediate masked (code that only moved data around);
 3. call-graph: matched pairs whose call lists line up pair their callees, repeated until nothing new.
"""
import difflib, hashlib, json, os, re, sys
from collections import defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
HERE = os.path.join(ROOT, "out", "tu")
# The vanilla <-> title-update address maps, committed: the title-update build translates our sources with them.
MAPS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "maps")
VANILLA = os.path.join(ROOT, "generated", "default")
# Generated by prepare.py --codegen.
TU = os.path.join(ROOT, "generated", "tu", "generated", "default")

DEFN = re.compile(r"DEFINE_REX_FUNC\(sub_([0-9A-Fa-f]{8})\)")
INSN = re.compile(r"^\s*// ([a-z][a-z0-9_.+-]*)(?:\s+(.*))?$")
CALL = re.compile(r"^bl 0x([0-9a-f]{8})$")


HELPER_CALL = re.compile(r"^\s*(__[a-z_]+\d*)\(ctx, base\);")
# Address of each register save/restore helper ("__savegprlr_22") a tree calls, filled by parse: they aren't functions.
helpers = {}


def parse(folder):
    funcs = {}
    names = helpers.setdefault(folder, {})
    pending = None
    for name in sorted(os.listdir(folder)):
        if not re.match(r".*recomp\.\d+\.cpp$", name):
            continue
        cur = None
        with open(os.path.join(folder, name), encoding="utf-8", errors="replace") as fh:
            for line in fh:
                m = DEFN.search(line)
                if m:
                    cur = int(m.group(1), 16)
                    funcs[cur] = []
                    continue
                if cur is None:
                    continue
                m = INSN.match(line)
                if m:
                    funcs[cur].append((m.group(1), (m.group(2) or "").strip()))
                    pending = m.group(2) if m.group(1) == "bl" else None
                    continue
                if pending and (h := HELPER_CALL.match(line)):
                    names[int(pending.strip(), 16)] = h.group(1)
                    pending = None
    return funcs


def norm(insns, loose):
    out = []
    for op, args in insns:
        if loose:
            args = re.sub(r"-?\b(0x[0-9a-fA-F]+|\d+)\b", "#", args)
        else:
            args = re.sub(r"0x[0-9a-fA-F]{6,8}", "@", args)
            # lis/addi/ld/st offsets against data move between builds
            if op in ("lis", "addis") or re.search(r"-?\d+\(r\d+\)", args) and op[0] in "ls":
                args = re.sub(r"-?\d+(?=\(r\d+\))", "#", args)
            if op in ("lis", "addis", "addi", "ori", "oris"):
                args = re.sub(r",-?\d+$", ",#", args)
        out.append(op + " " + args)
    return hashlib.sha1("\n".join(out).encode()).hexdigest()


def calls(insns):
    return [int(m.group(1), 16) for op, a in insns if (m := CALL.match(f"{op} {a}"))]


def _grams(insns):
    from collections import Counter
    ops = [o for o, _ in insns]
    return Counter(zip(ops, ops[1:], ops[2:]))


def similarity_round(vf, tf, mapping, used, pair, threshold=0.55):
    vs, ts = sorted(vf), sorted(tf)
    anchors = [(v, mapping[v]) for v in vs if v in mapping]
    vindex = {a: i for i, a in enumerate(vs)}
    tindex = {a: i for i, a in enumerate(ts)}
    added = 0
    for (v1, t1), (v2, t2) in zip(anchors, anchors[1:]):
        if t2 <= t1:
            continue
        vgap = [a for a in vs[vindex[v1] + 1:vindex[v2]] if a not in mapping and len(vf[a]) >= 8]
        tgap = [b for b in ts[tindex[t1] + 1:tindex[t2]] if b not in used and len(tf[b]) >= 8]
        if not vgap or not tgap or len(vgap) * len(tgap) > 4000:
            continue
        scores = []
        for a in vgap:
            ga = _grams(vf[a])
            ca = {mapping.get(c) for c in calls(vf[a])} - {None}
            for b in tgap:
                gb = _grams(tf[b])
                shape = sum((ga & gb).values()) / (sum((ga | gb).values()) or 1)
                cb = set(calls(tf[b]))
                share = len(ca & cb) / (len(ca | cb) or 1) if ca or cb else shape
                scores.append((shape * 0.6 + share * 0.4, a, b))
        for score, a, b in sorted(scores, reverse=True):
            if score < threshold:
                break
            added += pair(a, b)
    return added


def unique_join(vf, tf, vleft, tleft, loose):
    vs, ts = defaultdict(list), defaultdict(list)
    for a in vleft:
        if len(vf[a]) >= 4:
            vs[norm(vf[a], loose)].append(a)
    for a in tleft:
        if len(tf[a]) >= 4:
            ts[norm(tf[a], loose)].append(a)
    return {v[0]: ts[s][0] for s, v in vs.items() if len(v) == 1 and len(ts.get(s, [])) == 1}


def main():
    vf, tf = parse(VANILLA), parse(TU)
    print("functions: vanilla", len(vf), "tu", len(tf))
    mapping = {}
    for loose in (False, True):
        found = unique_join(vf, tf, set(vf) - set(mapping), set(tf) - set(mapping.values()), loose)
        mapping.update(found)
        print("round", "loose" if loose else "exact", "+", len(found), "=", len(mapping))
    used = set(mapping.values())

    def pair(a, b):
        if a in vf and b in tf and a not in mapping and b not in used:
            mapping[a] = b
            used.add(b)
            return 1
        return 0

    while True:
        added = 0
        # Calls: align each matched pair's call lists on the callees already matched, then pair the gaps of equal length.
        for v, t in list(mapping.items()):
            cv, ct = calls(vf[v]), calls(tf[t])
            if len(cv) == len(ct):
                for a, b in zip(cv, ct):
                    added += pair(a, b)
                continue
            sm = difflib.SequenceMatcher(None, [mapping.get(a, -a) for a in cv], ct, autojunk=False)
            for tag, i1, i2, j1, j2 in sm.get_opcodes():
                if tag == "replace" and i2 - i1 == j2 - j1:
                    for a, b in zip(cv[i1:i2], ct[j1:j2]):
                        added += pair(a, b)
        # Order: between two matched neighbours that keep their order, equal runs of unmatched functions pair up.
        vs = sorted(vf)
        anchors = [(v, mapping[v]) for v in vs if v in mapping]
        ts = sorted(tf)
        tindex = {a: i for i, a in enumerate(ts)}
        vindex = {a: i for i, a in enumerate(vs)}
        for (v1, t1), (v2, t2) in zip(anchors, anchors[1:]):
            if t2 <= t1:
                continue
            vgap = [a for a in vs[vindex[v1] + 1:vindex[v2]] if a not in mapping]
            tgap = [b for b in ts[tindex[t1] + 1:tindex[t2]] if b not in used]
            if vgap and len(vgap) == len(tgap) and len(vgap) <= 8:
                for a, b in zip(vgap, tgap):
                    # sizes within a factor of two, so a stray pairing of unrelated code is unlikely
                    if 0.5 <= (len(tf[b]) + 1) / (len(vf[a]) + 1) <= 2:
                        added += pair(a, b)
        print("round calls+order +", added, "=", len(mapping))
        if not added:
            # Similarity: within each gap between ordered anchors, pair functions whose instruction shape and mapped
            # callees agree well, best first. Reworked functions (a field added, a branch inserted) land here.
            added = similarity_round(vf, tf, mapping, used, pair)
            print("round similarity +", added, "=", len(mapping))
            if not added:
                break
    tu_new = sorted(set(tf) - used)
    van_gone = sorted(set(vf) - set(mapping))
    print("tu unmatched", len(tu_new), "insns", sum(len(tf[a]) for a in tu_new), "of", sum(len(x) for x in tf.values()))
    print("vanilla unmatched", len(van_gone), "insns", sum(len(vf[a]) for a in van_gone))
    json.dump({f"{v:08X}": f"{t:08X}" for v, t in sorted(mapping.items())}, open(os.path.join(MAPS, "map.json"), "w"), indent=0)
    with open(os.path.join(HERE, "tu_unmatched.txt"), "w") as f:
        for a in tu_new:
            f.write(f"{a:08X} {len(tf[a])}\n")
    with open(os.path.join(HERE, "vanilla_unmatched.txt"), "w") as f:
        for a in van_gone:
            f.write(f"{a:08X} {len(vf[a])}\n")


if __name__ == "__main__":
    main()
