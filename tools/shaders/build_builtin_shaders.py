#!/usr/bin/env python3
"""Compile the renderer's own HLSL into an embeddable C header.

These are OUR shaders (the Bink blit, and whatever follows), not the game's --
Kameo's own shaders go through XenosRecomp instead.

Emits both DXIL and SPIR-V so the same header serves plume's D3D12 and Vulkan
backends. Run it after editing anything under src/gpu/shaders/hlsl/ and commit the
generated header; it is not wired into CMake, so the build never depends on
having DXC present.

Usage:
  python tools/shaders/build_builtin_shaders.py
"""

import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHADER_DIR = os.path.join(ROOT, "src", "gpu", "shaders")
DXC = os.path.join(ROOT, "thirdparty", "XenosRecomp", "thirdparty", "dxc-bin",
                   "bin", "x64", "dxc.exe")

# (source, entry point, profile, symbol prefix)
TARGETS = [
    ("bink.hlsl", "VSMain", "vs_6_0", "g_binkVS"),
    ("bink.hlsl", "PSMain", "ps_6_0", "g_binkPS"),
    ("overlay.hlsl", "VSMain", "vs_6_0", "g_overlayVS"),
    ("overlay.hlsl", "PSMainRGBA", "ps_6_0", "g_overlayRgbaPS"),
    ("gamma.hlsl", "VSMain", "vs_6_0", "g_gammaVS"),
    ("gamma.hlsl", "PSMain", "ps_6_0", "g_gammaPS"),
    ("blit.hlsl", "VSMain", "vs_6_0", "g_blitVS"),
    ("blit.hlsl", "PSMain", "ps_6_0", "g_blitPS"),
    ("depth_resolve.hlsl", "VSMain", "vs_6_0", "g_depthResolveVS"),
    ("depth_resolve.hlsl", "PSMain", "ps_6_0", "g_depthResolvePS"),
    ("depth_resolve.hlsl", "PSSingle", "ps_6_0", "g_depthResolveSinglePS"),
    ("book_pick.hlsl", "PSMain", "ps_6_0", "g_bookPickPS"),
]


def compile_one(source, entry, profile, spirv):
    out = source + (".spv" if spirv else ".dxo")
    args = [DXC, "-T", profile, "-E", entry, "-Fo", out, source, "-O3"]
    if spirv:
        args += ["-spirv", "-fvk-use-dx-layout"]
        # Vulkan's NDC has Y pointing the opposite way to D3D12's, so a vertex
        # shader authored against D3D conventions renders vertically mirrored.
        # XenosRecomp passes this for every guest vertex shader
        # (dxc_compiler.cpp), which is why guest GEOMETRY was upright on Vulkan
        # while our own overlay and UI text -- built here, without it -- came
        # out flipped. Pixel shaders must NOT get it.
        if profile.startswith("vs_"):
            args.append("-fvk-invert-y")
    result = subprocess.run(args, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit("dxc failed for {}:{}\n{}".format(source, entry, result.stderr))
    with open(out, "rb") as f:
        data = f.read()
    os.remove(out)
    return data


def emit(f, name, data):
    f.write("inline constexpr unsigned char {}[] = {{\n".format(name))
    for i in range(0, len(data), 16):
        f.write("    " + "".join("0x%02X, " % b for b in data[i:i + 16]) + "\n")
    f.write("};\n\n")


def main():
    if not os.path.isfile(DXC):
        sys.exit("dxc not found at {}\n(clone thirdparty/XenosRecomp first)".format(DXC))

    header = os.path.join(SHADER_DIR, "builtin_shaders.h")
    with open(header, "w", newline="\n") as f:
        f.write("#pragma once\n\n")
        f.write("// Generated by tools/shaders/build_builtin_shaders.py -- do not edit.\n")
        f.write("// Sources: src/gpu/shaders/hlsl/\n\n")
        f.write("namespace kameo::gpu::shaders {\n\n")
        for source, entry, profile, prefix in TARGETS:
            path = os.path.join(SHADER_DIR, "hlsl", source)
            dxil = compile_one(path, entry, profile, spirv=False)
            spv = compile_one(path, entry, profile, spirv=True)
            print("{}:{} -> dxil {} bytes, spirv {} bytes".format(
                source, entry, len(dxil), len(spv)))
            emit(f, prefix + "Dxil", dxil)
            emit(f, prefix + "Spirv", spv)
        f.write("}  // namespace kameo::gpu::shaders\n")
    print("wrote", header)


if __name__ == "__main__":
    main()
