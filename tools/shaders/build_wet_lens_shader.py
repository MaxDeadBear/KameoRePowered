"""Embed the wet-lens vertex shader with texture coordinates taken from NDC positions."""

import pathlib
import subprocess
import tempfile

from build_builtin_shaders import DXC, emit
from build_particle_shaders import COMMON, RECOMP, replace_once

ROOT = pathlib.Path(__file__).resolve().parents[2]
SHADERS = ROOT / "src/gpu/shaders"
CONTAINER = SHADERS / "wet_lens/B0B81D68886E069D.bin"


def vertex_source(source):
    return replace_once(source, "r0.xy = r1.xy * c11.xy;", "r0.xy = r1.xy * float2(0.5, -0.5) + 0.5;")


def main():
    with tempfile.TemporaryDirectory() as temp:
        work = pathlib.Path(temp)
        vs = work / "wet_lens_vs.hlsl"
        subprocess.run([str(RECOMP), str(CONTAINER), str(vs), str(COMMON)], check=True)
        vs.write_text(vertex_source(vs.read_text()))
        blobs = []
        for spirv in (False, True):
            output = work / "shader.bin"
            args = [DXC, "-T", "vs_6_0", "-E", "main", "-Fo", str(output), str(vs), "-O3"]
            if spirv:
                args += ["-spirv", "-fvk-use-dx-layout", "-fvk-invert-y"]
            subprocess.run(args, check=True)
            blobs.append(("g_wetLensVS" + ("Spirv" if spirv else "Dxil"), output.read_bytes()))
        with (SHADERS / "wet_lens_shaders.h").open("w", newline="\n") as header:
            header.write("#pragma once\n\n// Generated by tools/shaders/build_wet_lens_shader.py.\nnamespace kameo::gpu::shaders {\n")
            for symbol, data in blobs:
                emit(header, symbol, data)
                print(symbol, len(data))
            header.write("}\n")


if __name__ == "__main__":
    main()
