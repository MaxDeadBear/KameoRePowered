"""Embed verified point-sprite shader pairs with native point-sprite support."""

import pathlib
import re
import subprocess
import tempfile

from build_builtin_shaders import DXC, emit

ROOT = pathlib.Path(__file__).resolve().parents[2]
SHADERS = ROOT / "src/gpu/shaders"
RECOMP = ROOT / "thirdparty/XenosRecomp/build/XenosRecomp/Release/XenosRecomp.exe"
COMMON = ROOT / "thirdparty/XenosRecomp/XenosRecomp/shader_common.h"
CONTAINERS = SHADERS / "particles"

# (symbol prefix, vertex shader, pixel shader, the pixel shader's point-sprite parameter register)
SPRITES = [
    ("mote", "67EDA3D674722EC6", "9A16289A84E5A85B", "r2"),
    ("spray", "511A3E3E3F0761D3", "E1D5926C5F6332C6", "r1"),
    ("burst", "04D58836F1C8402F", "84162BFF585D487A", "r2"),
]


def replace_once(source, old, new):
    if source.count(old) != 1:
        raise ValueError(f"Expected one occurrence of {old!r}")
    return source.replace(old, new)


def translate(shader_hash, output):
    # XenosRecomp crashes intermittently; build_shader_cache.py retries it the same way.
    for _ in range(8):
        if subprocess.run([str(RECOMP), str(CONTAINERS / f"{shader_hash}.bin"), str(output), str(COMMON)]).returncode == 0 and output.exists():
            return output.read_text()
    raise RuntimeError(f"XenosRecomp failed on {shader_hash}")


def vertex_source(source):
    source = re.sub(r"\t(?:out float4 oTexCoord\d+ : TEXCOORD\d+,?\n|oTexCoord\d+ = 0\.0;\n)", "", source)
    source = replace_once(source, "out float4 oColor0 : COLOR0", "[[vk::location(0)]] out float4 oColor0 : COLOR0")
    source = replace_once(source, "out float4 oColor1 : COLOR1", "[[vk::location(1)]] out float4 oColor1 : COLOR1,\n\t[[vk::location(2)]] out float oPointSize : PSIZE0")
    return replace_once(source, "r63.x = max(r0.x, r0.x);", "oPointSize = max(r0.x, r0.x);")


def pixel_source(source, param):
    source = re.sub(r"\tin float4 iTexCoord(?:[1-9]|1[0-5]) : TEXCOORD\d+,\n", "", source)
    source = replace_once(source, "in float4 iTexCoord0 : TEXCOORD0", "[[vk::location(2)]] in float2 iTexCoord0 : TEXCOORD0")
    source = replace_once(source, "in float4 iColor0 : COLOR0", "[[vk::location(0)]] in float4 iColor0 : COLOR0")
    source = replace_once(source, "in float4 iColor1 : COLOR1", "[[vk::location(1)]] in float4 iColor1 : COLOR1")
    return replace_once(source, f"float4 {param} = 0.0;", f"float4 {param} = float4(abs(iPos.x), -abs(iPos.y), saturate(iTexCoord0));")


def compile_blobs(source, profile, symbol, work):
    blobs = []
    for spirv in (False, True):
        output = work / "shader.bin"
        args = [DXC, "-T", profile, "-E", "main", "-Fo", str(output), str(source), "-O3"]
        if spirv:
            args += ["-spirv", "-fvk-use-dx-layout"]
            if profile.startswith("vs_"):
                args.append("-fvk-invert-y")
        subprocess.run(args, check=True)
        blobs.append((symbol + ("Spirv" if spirv else "Dxil"), output.read_bytes()))
    return blobs


def main():
    with tempfile.TemporaryDirectory() as temp:
        work = pathlib.Path(temp)
        blobs = []
        for name, vs_hash, ps_hash, param in SPRITES:
            vs = work / f"{name}_vs.hlsl"
            ps = work / f"{name}_ps.hlsl"
            vs.write_text(vertex_source(translate(vs_hash, vs)))
            ps.write_text(pixel_source(translate(ps_hash, ps), param))
            blobs += compile_blobs(vs, "vs_6_0", f"g_{name}VS", work)
            blobs += compile_blobs(ps, "ps_6_0", f"g_{name}PS", work)
        blobs += compile_blobs(SHADERS / "point_sprite.hlsl", "gs_6_0", "g_pointSpriteGS", work)
        with (SHADERS / "particle_shaders.h").open("w", newline="\n") as header:
            header.write("#pragma once\n\n// Generated by tools/shaders/build_particle_shaders.py.\nnamespace kameo::gpu::shaders {\n")
            for symbol, data in blobs:
                emit(header, symbol, data)
                print(symbol, len(data))
            header.write("}\n")


if __name__ == "__main__":
    main()
